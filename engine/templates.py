def scaffold(competition_dir: Path, slug: str, title: str | None = None,
             target: str | None = None, metric: str | None = None,
             target_score: float | None = None, force: bool = False) -> dict[str, Path]:
    """Create the R1 folder contract. Never overwrites user work unless forced."""
    code_dir = competition_dir / "code"
    datasets_dir = competition_dir / "datasets"
    train_dir = competition_dir / "train"
    for directory in (code_dir, datasets_dir, train_dir):
        directory.mkdir(parents=True, exist_ok=True)

    for directory in (datasets_dir, train_dir):
        keep = directory / ".gitkeep"
        if not keep.exists():
            keep.write_text(GITKEEP, encoding="utf-8")

    notebook_path = code_dir / f"{slug}.ipynb"
    if force or not notebook_path.exists():
        nb = starter_notebook(slug, target=target, metric=metric, target_score=target_score)
        nbformat.write(nb, notebook_path)

    readme_path = competition_dir / "readme.md"
    if force or not readme_path.exists():
        readme_path.write_text(
            competition_readme(slug, title, target, metric, target_score), encoding="utf-8"
        )

    return {"code": notebook_path, "readme": readme_path,
            "datasets": datasets_dir, "train": train_dir}
