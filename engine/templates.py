_SCORE_MATCHING = """## Score matching (rule R5)

`../train/metrics.json` now holds the measured OOF score. Copy it into
`../readme.md` — never invent a number (R4).

- Gate target: `TARGET_SCORE`
- Direction: higher-is-better unless the metric is RMSE / MAE / log-loss.
- If the gate is not met, the engine feeds the gap back to the coding agent and
  the next attempt climbs the R7 ladder: domain features → model zoo →
  OOF-fitted ensemble → fold-safe target encoding → pseudo-labelling →
  bounded hyperparameter search.
"""


def starter_notebook(slug: str, target: str | None = None,
                     metric: str | None = None,
                     target_score: float | None = None,
                     n_splits: int = 5) -> nbformat.NotebookNode:
    """Build the baseline notebook as an nbformat document."""
    replacements = {
        "__SLUG__": slug,
        "__TARGET__": repr(target) if target else "None",
        "__METRIC__": repr(metric) if metric else "None",
        "__TARGET_SCORE__": repr(target_score) if target_score is not None else "None",
        "__NSPLITS__": str(n_splits),
    }

    def fill(text: str) -> str:
        for key, value in replacements.items():
            text = text.replace(key, value)
        return text

    nb = new_notebook()
    nb.metadata.update({
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "pygments_lexer": "ipython3"},
        "engine": {"rules_version": "1.0.0", "generator": "python -m engine init"},
    })
    cells = [
        new_markdown_cell(fill(_NOTEBOOK_HEADER)),
        new_code_cell(fill(_CONFIG)),
        new_code_cell(_IMPORTS),
        new_code_cell(_LOAD),
        new_code_cell(_TARGET),
        new_code_cell(_TASK),
        new_code_cell(_FEATURES),
        new_code_cell(_HELPERS),
        new_code_cell(_TRAIN),
        new_code_cell(_METRICS),
        new_code_cell(_SUBMISSION),
        new_markdown_cell(_SCORE_MATCHING),
    ]
    nb.cells = cells
    return nb


