def competition_readme(slug: str, title: str | None, target: str | None,
                       metric: str | None, target_score: float | None) -> str:
    text = _README
    text = text.replace("__SLUG__", slug)
    text = text.replace("__TITLE__", title or slug)
    text = text.replace("__TARGET__", target or "_auto-detected_")
    text = text.replace("__METRIC__", metric or "_to be confirmed from the Kaggle evaluation page_")
    text = text.replace("__TARGET_SCORE__", str(target_score) if target_score is not None else "_not set_")
    return text


