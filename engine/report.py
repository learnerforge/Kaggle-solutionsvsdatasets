"""Reporting: per-competition run reports and the frontend dashboard feed.

Two audiences:

* ``competition/<slug>/train/report.md`` — the human-readable attempt log:
  what the coder was asked, what it did, what was measured, which checks
  failed, what the next ladder step is.
* ``frontend/data/dashboard.json`` — the machine-readable projection the static
  frontend reads: competitions, scores, gate status, requirement matrix.
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timezone
from pathlib import Path

from . import rules, scorer, store, validate
from .settings import Settings, load

DEFAULT_REPO_URL = "https://github.com/learnerforge/Kaggle-solutionsvsdatasets"

PIPELINE_STAGES = [
    ("1. scout", "Fetch problem statement, metric, file list and dataset profile "
                 "(engine/scout.py)"),
    ("2. scaffold", "Enforce the folder contract and materialise a runnable baseline "
                    "(engine/templates.py)"),
    ("3. code", "Trigger OpenCode to write/repair the notebook under the rulebook "
                "(engine/opencode_runner.py)"),
    ("4. execute", "Run the notebook top-to-bottom, keep a partial copy on failure "
                   "(engine/notebook_runner.py)"),
    ("5. score", "Read train/metrics.json and compare against the gate; never invent a "
                 "number (engine/scorer.py)"),
    ("6. iterate", "Feed the gap back and climb the R7 ladder, at most ENGINE_MAX_ATTEMPTS "
                   "times (engine/orchestrator.py)"),
    ("7. report", "Write train/report.md and refresh the frontend dashboard "
                  "(engine/report.py)"),
]


def repo_url() -> str:
    return os.environ.get("ENGINE_REPO_URL", DEFAULT_REPO_URL).rstrip("/")


def write_attempt_report(slug: str, *, attempt: int, checks: dict | None,
                         report: scorer.ScoreReport | None, feedback: str | None,
                         coder_message: str | None, execution_error: str | None,
                         settings: Settings | None = None) -> Path:
    settings = settings or load()
    path = settings.train_dir(slug) / "report.md"
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    comp = store.get_competition(slug, settings) or {}
    history = store.history(slug, limit=30, settings=settings)

    lines = [
        f"# Run report — {comp.get('title') or slug}",
        "",
        f"* Generated: {now}",
        f"* Rulebook: v{rules.RULEBOOK_VERSION}",
        f"* Metric: `{comp.get('metric') or 'unknown'}` "
        f"({'higher' if comp.get('higher_is_better', 1) else 'lower'} is better)",
        f"* Score gate: `{comp.get('target_score') if comp.get('target_score') is not None else 'not set'}`",
        f"* Attempt: {attempt} of {settings.max_attempts}",
        "",
    ]

    if report is not None:
        lines += [
            "## Score",
            "",
            f"* `{report.summary()}`",
        ]
        if report.notes:
            lines += ["", "### Diagnostics", ""] + [f"* {note}" for note in report.notes]
        lines.append("")

    if checks is not None:
        lines += ["## Requirement checks", "", "| rule | requirement | status | evidence |",
                  "| --- | --- | --- | --- |"]
        for check in checks.get("checks", []):
            lines.append(f"| {check['rule']} | {check['title']} | `{check['status']}` | "
                         f"{check['detail']} |")
        lines.append("")

    if execution_error:
        lines += ["## Execution error", "", "```", execution_error.strip()[-2000:], "```", ""]

    if feedback:
        lines += ["## Next-attempt feedback", "", feedback.strip(), ""]

    if coder_message:
        lines += ["## Coder report (communication record)", "", coder_message.strip(), ""]

    if history:
        lines += ["## Run history", "", "| attempt | phase | status | OOF | finished |",
                  "| --- | --- | --- | --- | --- |"]
        for row in history:
            oof = "" if row.get("cv_mean") is None else f"{row['cv_mean']:.5f}"
            lines.append(f"| {row['attempt']} | {row['phase']} | {row['status']} | {oof} | "
                         f"{row.get('finished_at') or ''} |")
        lines.append("")

    lines += [
        "---",
        "",
        "_Generated by `python -m engine report`. Source of truth for numbers: "
        "`train/metrics.json` (rule R4)._",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _competition_view(slug: str, settings: Settings) -> dict:
    comp = store.get_competition(slug, settings) or {"slug": slug}
    report = scorer.evaluate(slug, settings=settings)
    history = store.history(slug, limit=10, settings=settings)
    checks_path = settings.train_dir(slug) / "checks.json"
    checks = None
    if checks_path.is_file():
        try:
            checks = json.loads(checks_path.read_text(encoding="utf-8"))
        except ValueError:
            checks = None
    if checks is None:
        checks = validate.run_all(slug, settings=settings,
                                  artifacts_expected=scorer.metrics_path(slug, settings).is_file())

    base = repo_url()
    return {
        "slug": slug,
        "title": comp.get("title") or slug,
        "url": f"https://www.kaggle.com/competitions/{slug}",
        "metric": report.metric,
        "task": report.task,
        "higher_is_better": report.higher_is_better,
        "target_score": report.target_score,
        "cv_mean": report.cv_mean,
        "cv_std": report.cv_std,
        "cv_folds": report.cv_folds,
        "oof_score": report.oof_score,
        "lb_score": report.lb_score,
        "gap": report.gap,
        "reached": report.reached,
        "notes": report.notes,
        "status": comp.get("status") or "registered",
        "attempts": len(history),
        "last_attempt_at": history[0].get("finished_at") if history else None,
        "readme_url": f"{base}/blob/main/competition/{slug}/readme.md",
        "notebook_url": f"{base}/blob/main/competition/{slug}/code/{slug}.pynb",
        "problem_statement_url": f"{base}/blob/main/competition/{slug}/PROBLEM_STATEMENT.md",
        "brief_url": f"{base}/blob/main/competition/{slug}/BRIEF.md",
        "checks": checks.get("checks", []),
        "checks_failed": checks.get("failed", []),
        "checks_passed": checks.get("passed", False),
        "history": [
            {
                "attempt": row["attempt"],
                "phase": row["phase"],
                "status": row["status"],
                "cv_mean": row["cv_mean"],
                "lb_score": row["lb_score"],
                "score_reached": None if row["score_reached"] is None else bool(row["score_reached"]),
                "finished_at": row.get("finished_at"),
                "notes": row.get("notes"),
            }
            for row in history
        ],
    }


def build_dashboard(settings: Settings | None = None) -> dict:
    settings = settings or load()
    known = {c["slug"] for c in store.list_competitions(settings)}
    on_disk = set()
    if settings.competitions_root.is_dir():
        on_disk = {p.name for p in settings.competitions_root.iterdir() if p.is_dir()}
    slugs = sorted(known | on_disk)

    competitions = [_competition_view(slug, settings) for slug in slugs]
    solved = [c for c in competitions if c["reached"] is True]
    stats = store.cycle_stats(settings)
    stats.update({
        "gate_reached": len(solved),
        "tracked_on_disk": len(on_disk),
        "gate_defined": sum(1 for c in competitions if c["target_score"] is not None),
    })

    try:
        from . import secrets

        auth = secrets.auth_ready(settings)
    except Exception:  # noqa: BLE001
        auth = False

    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "rules_version": rules.RULEBOOK_VERSION,
        "repo_url": repo_url(),
        "engine": {
            "max_attempts": settings.max_attempts,
            "notebook_timeout": settings.notebook_timeout,
            "opencode_model": settings.opencode_model or "default",
            "opencode_agent": settings.opencode_agent or "default",
            "submit_enabled": settings.submit_enabled,
            "kaggle_auth_ready": auth,
            "vercel_sync": bool(settings.vercel_sync_url),
        },
        "stats": stats,
        "competitions": competitions,
        "requirements": [
            {"id": rid, "title": title, "text": text} for rid, title, text in rules.RULES
        ],
        "pipeline": [{"stage": stage, "description": description}
                     for stage, description in PIPELINE_STAGES],
    }


def write_dashboard(settings: Settings | None = None) -> Path:
    settings = settings or load()
    payload = build_dashboard(settings)
    settings.frontend_data.mkdir(parents=True, exist_ok=True)
    path = settings.frontend_data / "dashboard.json"
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return path
